## 🚀 Como Usar

1. **Navegue pelos módulos** na ordem sugerida
2. **Assista as aulas** com áudio explicativo
3. **Pratique com exercícios** de diferentes níveis
4. **Estude os exemplos** de código fornecidos
5. **Use os recursos** adicionais para aprofundar

## 📖 Recursos Adicionais

- [Documentação do Curso](docs/)
- [Exemplos de Código](examples/)
- [Exercícios Práticos](exercises/)

---

*Curso criado e mantido como projeto open source.*
EOF
    
    log_success "Updated index page"
    return 0
}

# Create module index pages
create_module_index_pages() {
    local dry_run="$1"
    
    log_info "Creating module index pages..."
    
    if [[ "$dry_run" == "true" ]]; then
        log_info "WOULD CREATE: Index pages for each module"
        return 0
    fi
    
    # Create index page for each module
    get_all_module_mappings | while IFS='|' read -r old_name new_id new_title; do
        local module_dir="modules/$new_id"
        
        if [[ -d "$module_dir" ]]; then
            cat > "$module_dir/index.md" << EOF
---
layout: module
title: "$new_title"
module_id: $new_id
description: "Módulo $new_id do curso de Estrutura de Dados e Algoritmos"
---

# $new_title

## 📖 Sobre este Módulo

Este módulo aborda os conceitos fundamentais de **$new_title**.

## 📚 Conteúdo

### Aulas
{% assign lessons = site.pages | where: "module_id", "$new_id" | where: "content_type", "lesson" %}
{% for lesson in lessons %}
- [{{ lesson.title }}]({{ lesson.url | relative_url }})
{% endfor %}

### Exercícios
{% assign exercises = site.pages | where: "module_id", "$new_id" | where: "content_type", "exercise" %}
{% for exercise in exercises %}
- [{{ exercise.title }}]({{ exercise.url | relative_url }})
{% endfor %}

### Exemplos
{% assign examples = site.pages | where: "module_id", "$new_id" | where: "content_type", "example" %}
{% for example in examples %}
- [{{ example.title }}]({{ example.url | relative_url }})
{% endfor %}

## 🎧 Recursos de Áudio

Os áudios deste módulo estão disponíveis em: \`assets/audio/$new_id/\`

---

[← Voltar ao Curso]({{ site.baseurl }}/) | [Próximo Módulo →]()
EOF
        fi
    done
    
    log_success "Created module index pages"
    return 0
}

# Update asset references in existing files
update_asset_references() {
    local dry_run="$1"
    
    log_info "Updating asset references..."
    
    if [[ "$dry_run" == "true" ]]; then
        log_info "WOULD UPDATE: Asset references in CSS/JS files"
        return 0
    fi
    
    # Update CSS files
    find assets/css -name "*.css" -type f 2>/dev/null | while read -r css_file; do
        if [[ -f "$css_file" ]]; then
            sed -i.bak 's|src/modulos-treinamento/|modules/|g' "$css_file" 2>/dev/null || true
            rm -f "$css_file.bak" 2>/dev/null || true
        fi
    done
    
    # Update JS files
    find assets/js -name "*.js" -type f 2>/dev/null | while read -r js_file; do
        if [[ -f "$js_file" ]]; then
            sed -i.bak 's|src/modulos-treinamento/|modules/|g' "$js_file" 2>/dev/null || true
            rm -f "$js_file.bak" 2>/dev/null || true
        fi
    done
    
    log_success "Updated asset references"
    return 0
}

# Create basic Jekyll config if none exists
create_basic_jekyll_config() {
    cat > "_config.yml" << 'EOF'
# Jekyll Configuration for Estrutura de Dados e Algoritmos

title: "Estrutura de Dados e Algoritmos"
description: "Curso completo de estruturas de dados e algoritmos"
baseurl: ""
url: ""

# Build settings
markdown: kramdown
highlighter: rouge
theme: minima

# Collections
collections:
  modules:
    output: true
    permalink: /:collection/:name/

# Plugins
plugins:
  - jekyll-sitemap
  - jekyll-feed

# Exclude files
exclude:
  - Gemfile
  - Gemfile.lock
  - scripts/
  - backups/
  - README.md

# Include files
include:
  - .htaccess

# Pagination
paginate: 10
paginate_path: "/page:num/"

# Default front matter
defaults:
  - scope:
      path: "modules"
    values:
      layout: "module"
      course: "estrutura-de-dados-e-algoritmos"
EOF
}

# Rollback configuration updates
rollback_phase6() {
    local backup_id="$1"
    
    log_info "Rolling back Phase 6: Configuration Updates (Backup ID: $backup_id)"
    
    # Restore backup files
    find . -name "*.backup.*" -type f 2>/dev/null | while read -r backup_file; do
        local original_file="${backup_file%%.backup.*}"
        if [[ -f "$backup_file" ]]; then
            mv "$backup_file" "$original_file"
            log_info "Restored: $original_file"
        fi
    done
    
    # Remove generated files
    rm -f "_data/new_course_structure.yml" 2>/dev/null || true
    rm -f "_includes/module_navigation.html" 2>/dev/null || true
    rm -f "_includes/audio_player.html" 2>/dev/null || true
    
    # Remove module index pages
    find modules -name "index.md" -type f -delete 2>/dev/null || true
    
    log_success "Phase 6 rollback completed"
}

# Main execution (if script is run directly)
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    DRY_RUN="${1:-false}"
    phase6_config_updates "$DRY_RUN"
fi 